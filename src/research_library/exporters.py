"""Exports: CSV, JSONL, BibTeX (from SQLite source of truth)."""

from __future__ import annotations

import csv
import json
import re
from pathlib import Path

from . import db
from .normalize import norm_doi

BIB_TYPE_MAP = {
    "journal_article": "article",
    "conference_paper": "inproceedings",
    "review_article": "article",
    "report": "techreport",
    "practice_guide": "techreport",
    "guideline": "techreport",
    "book": "book",
    "book_chapter": "incollection",
    "preprint": "misc",
    "eric_document": "techreport",
    "dissertation": "phdthesis",
}


def ingested_works(conn):
    rows = conn.execute(
        "SELECT * FROM works WHERE record_status='ingested' ORDER BY"
        " COALESCE(research_domains,'[]'), publication_year, internal_id"
    ).fetchall()
    return [db.row_to_dict(r) for r in rows]


def _flatten_authors(authors: list) -> str:
    return "; ".join(a.get("name") or "" for a in authors or [] if a.get("name"))


def export_csv(conn, out_path: Path) -> int:
    works = ingested_works(conn)
    cols = [c for c in db.WORK_COLUMNS if c != "raw_sources"]
    out_path = Path(out_path)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with open(out_path, "w", newline="", encoding="utf-8-sig") as f:
        writer = csv.writer(f)
        writer.writerow(cols)
        for w in works:
            row = []
            for c in cols:
                v = w.get(c)
                if c in db.JSON_FIELDS and isinstance(v, list):
                    if c == "authors":
                        v = _flatten_authors(v)
                    else:
                        v = "; ".join(str(x) for x in v)
                elif isinstance(v, (dict, list)):
                    v = json.dumps(v, ensure_ascii=False)
                row.append("" if v is None else v)
            writer.writerow(row)
    return len(works)


def export_jsonl(conn, out_path: Path) -> int:
    works = ingested_works(conn)
    out_path = Path(out_path)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with open(out_path, "w", encoding="utf-8") as f:
        for w in works:
            f.write(json.dumps(w, ensure_ascii=False, default=str) + "\n")
    return len(works)


def _bib_escape(s: str) -> str:
    return s.replace("\\", "\\textbackslash{}").replace("&", "\\&").replace("%", "\\%")\
            .replace("_", "\\_").replace("#", "\\#").replace("$", "\\$")


def _bib_authors(authors: list) -> str:
    parts = []
    for a in authors or []:
        family = a.get("family")
        given = a.get("given")
        name = a.get("name") or ""
        if family:
            parts.append(f"{family}, {given}" if given else family)
        elif name:
            parts.append(name)
    return " and ".join(_bib_escape(p) for p in parts)


def _bib_pages(pages: str | None) -> str | None:
    if not pages:
        return None
    return str(pages).replace("-", "--")


def export_bibtex(conn, out_path: Path) -> int:
    works = ingested_works(conn)
    out_path = Path(out_path)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    lines = ["% BibTeX export - ChildEvidence Research Library v0.1",
             "% Generated from library.sqlite; generated by research-library pipeline.", ""]
    count = 0
    for w in works:
        entry_type = BIB_TYPE_MAP.get(w.get("document_type") or "", "misc")
        key = w["internal_id"].replace("-", "")
        fields = []
        fields.append(("author", _bib_authors(w.get("authors"))))
        fields.append(("title", "{{{}}}".format(_bib_escape(w.get("title") or ""))))
        year = w.get("publication_year")
        if year:
            fields.append(("year", str(year)))
        journal = w.get("journal_or_publisher")
        if journal and entry_type in ("article", "inproceedings"):
            fields.append(("journal", _bib_escape(str(journal))))
        elif journal:
            fields.append(("institution" if entry_type == "techreport" else "publisher",
                           _bib_escape(str(journal))))
        if w.get("volume"):
            fields.append(("volume", str(w["volume"])))
        if w.get("issue"):
            fields.append(("number", str(w["issue"])))
        pages = _bib_pages(w.get("pages"))
        if pages:
            fields.append(("pages", pages))
        doi = norm_doi(w.get("doi"))
        if doi:
            fields.append(("doi", doi))
        if w.get("canonical_url"):
            fields.append(("url", w["canonical_url"]))
        issn = w.get("issn") or []
        if issn:
            fields.append(("issn", "; ".join(issn)))
        if w.get("language"):
            fields.append(("language", w["language"]))
        notes = []
        if w.get("document_type") == "preprint":
            notes.append("preprint, not peer reviewed")
        notes.append(f"access: {w.get('access_status')}")
        if w.get("pdf_version"):
            notes.append(f"pdf version: {w['pdf_version']}")
        fields.append(("note", "; ".join(notes)))
        body = ",\n".join(f"  {k} = {{{v}}}" for k, v in fields if v)
        lines.append(f"@{entry_type}{{{key},\n{body}\n}}")
        lines.append("")
        count += 1
    out_path.write_text("\n".join(lines), encoding="utf-8")
    return count


def export_all(conn, out_dir: Path) -> dict:
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    return {
        "csv": export_csv(conn, out_dir / "works.csv"),
        "jsonl": export_jsonl(conn, out_dir / "works.jsonl"),
        "bibtex": export_bibtex(conn, out_dir / "works.bib"),
    }
